#
#   make-stubs.py <link errors> <stubs.S> <object>...
#
# bp_pcsx2.cpp names hundreds of PCSX2 and console functions; the pages call a handful of them
# while they are made. The link's undefined symbols (read from its errors) become stubs: a function
# (one the objects call: an R_X86_64_PLT32 relocation) jumps to crux2_inventory_missing with its
# name, which says which and stops the program; anything else (a variable, a vtable) is 64 KiB of
# zeros. So the inventory never runs code it has not got, and says so when a page needs some.
import re
import subprocess
import sys
from pathlib import Path


def main():
    errors, out, objects = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3:]
    text = errors.read_text(errors="replace")
    names = set(re.findall(r"undefined reference to `([^']+)'", text))
    names |= set(re.findall(r"undefined symbol: (\S+)", text))
    if not names:
        print("make-stubs: no undefined symbol in the link's errors", file=sys.stderr)
        return 1
    called = set()
    for obj in objects:
        relocs = subprocess.run(["readelf", "-rW", obj], capture_output=True, text=True).stdout
        for line in relocs.splitlines():
            parts = line.split()
            if len(parts) >= 5 and parts[2] == "R_X86_64_PLT32":
                called.add(parts[4])
    old = out.read_text() if out.exists() else ""
    have = set(re.findall(r"^\.globl (\S+)$", old, re.M))
    lines = [old.rstrip("\n")] if old else ["# Generated by make-stubs.py: the symbols the inventory does not have.",
                                            "\t.section .note.GNU-stack,\"\",@progbits"]
    added = 0
    for i, name in enumerate(sorted(names - have)):
        label = f".Lname{len(have) + i}"
        if name in called and not name.startswith(("_ZTV", "_ZTI", "_ZTS")):
            lines += ["\t.text", f".globl {name}", f"\t.type {name}, @function", f"{name}:",
                      f"\tleaq {label}(%rip), %rdi", "\tjmp crux2_inventory_missing@PLT",
                      "\t.section .rodata", f"{label}:", f"\t.asciz \"{name}\""]
        else:
            lines += ["\t.bss", "\t.balign 64", f".globl {name}", f"\t.type {name}, @object", f"\t.size {name}, 65536",
                      f"{name}:", "\t.zero 65536"]
        added += 1
    out.write_text("\n".join(lines) + "\n")
    print(f"make-stubs: {added} stub(s) added, {len(have) + added} in all")
    return 0


if __name__ == "__main__":
    sys.exit(main())
